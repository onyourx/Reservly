const Ctx = createContext<{ language: UiLanguage; setLanguage: (v: UiLanguage) => void; t: (s: string) => string } | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const initial = (localStorage.getItem("reservly-ui-language") || "en") as UiLanguage;
  const [language, setState] = useState<UiLanguage>(["en", "fr", "es"].includes(initial) ? initial : "en");
  const value = useMemo(() => ({
    language,
    setLanguage: (next: UiLanguage) => { localStorage.setItem("reservly-ui-language", next); setState(next); },
    t: (source: string) => messages[language][source] || source,
  }), [language]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const value = useContext(Ctx);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export const languageName = (locale: string) =>
  ({ en: "English", fr: "Français", es: "Español" } as Record<string, string>)[locale] || locale.toUpperCase();
